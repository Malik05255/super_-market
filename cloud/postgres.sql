drop policy if exists "public read snapshots" on product_snapshots;
create policy "public read snapshots" on product_snapshots for select using (true);

drop policy if exists "public read system state" on system_state;
create policy "public read system state" on system_state for select using (true);

grant select on product_price_snapshot to anon, authenticated;
revoke all on retailer_product_sources from anon, authenticated;
revoke all on price_periods from anon, authenticated;
revoke all on product_snapshots from anon, authenticated;
grant select on product_snapshots to anon, authenticated;
grant select on system_state to anon, authenticated;
